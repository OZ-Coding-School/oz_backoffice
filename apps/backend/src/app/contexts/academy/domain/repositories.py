import uuid
from typing import Protocol

from app.contexts.academy.domain.entities import (
    Bootcamp,
    Cohort,
    HrdNetBootcamp,
    HrdNetBootcampCohort,
    RosterSyncRun,
    Student,
    StudentRoster,
)


class HrdNetBootcampRepository(Protocol):
    async def add(self, bootcamp: HrdNetBootcamp) -> None: ...
    async def save(self, bootcamp: HrdNetBootcamp) -> None: ...
    async def get(self, entity_id: uuid.UUID) -> HrdNetBootcamp | None: ...


class HrdNetBootcampCohortRepository(Protocol):
    async def add(self, cohort: HrdNetBootcampCohort) -> None: ...
    async def save(self, cohort: HrdNetBootcampCohort) -> None: ...
    async def get(self, entity_id: uuid.UUID) -> HrdNetBootcampCohort | None: ...


class BootcampRepository(Protocol):
    async def add(self, bootcamp: Bootcamp) -> None: ...
    async def save(self, bootcamp: Bootcamp) -> None: ...
    async def get(self, entity_id: uuid.UUID) -> Bootcamp | None: ...
    async def get_by_code(self, code: str) -> Bootcamp | None: ...


class CohortRepository(Protocol):
    async def add(self, cohort: Cohort) -> None: ...
    async def save(self, cohort: Cohort) -> None: ...
    async def get(self, entity_id: uuid.UUID) -> Cohort | None: ...
    async def get_by_number(self, bootcamp_id: uuid.UUID, cohort_number: int) -> Cohort | None: ...
    async def list_by_bootcamp(self, bootcamp_id: uuid.UUID) -> list[Cohort]: ...


class StudentRepository(Protocol):
    async def add(self, student: Student) -> None: ...
